"""
Aula 4 - Tipo int e float (numeros) - introducao aos tipos de dados
int -> Numero inteiro
O tipo int representa qualquer numero
positivo ou negativo. int sem sinal é considerado positivo
"""
print(11) #int
print(-11) #int
print(0)

"""
Float -> Numero com ponto flutuante
o tipo float representa qualquer numero
positivo ou negativo com ponto flutuante.
float sem sinal é considerato positivo
"""
print(1.1, 10.11)
print(0.0, -1.5)

"""
A funcao type mostra o tipo que o python inteferiu ao valor
"""
print(type('texto'))
print(type(1))
print(type(1.0), type(-1.1), type(0.0))